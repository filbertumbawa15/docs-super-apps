-- Skema database SKCK & Izin Keramaian + Verifiable Credential (VC)
-- Disusun dari atribut API lookup (POST /api/v1/external/service-applications/lookup)
-- dan struktur W3C VC 2.0 di vc.html.
--
-- Aman dijalankan ulang (IF NOT EXISTS / CREATE OR REPLACE).
-- Dipanggil oleh install-postgres.sh:  psql -v app_user=skck_app -f schema.sql

\set ON_ERROR_STOP on
SET client_min_messages = warning;

CREATE SCHEMA IF NOT EXISTS layanan;
SET search_path = layanan, public;

-- Pembaruan kolom updated_at otomatis ------------------------------------------
CREATE OR REPLACE FUNCTION layanan.set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

-- 1. Pemohon (data.user) -------------------------------------------------------
CREATE TABLE IF NOT EXISTS pemohon (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- user.id
  nik         char(16)    NOT NULL UNIQUE CHECK (nik ~ '^[0-9]{16}$'),
  full_name   text        NOT NULL,                                  -- user.full_name
  holder_did  text        UNIQUE,                                    -- credentialSubject.id
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE pemohon IS 'Pemohon layanan; dipetakan ke data.user pada respons lookup.';

-- 2. Pengajuan SKCK (data.skck[]) ----------------------------------------------
CREATE TABLE IF NOT EXISTS pengajuan_skck (
  id                  char(26)    PRIMARY KEY CHECK (id ~ '^[0-9A-HJKMNP-TV-Z]{26}$'),  -- ULID
  pemohon_id          bigint      NOT NULL REFERENCES pemohon(id) ON DELETE RESTRICT,
  registration_number text        NOT NULL UNIQUE,
  status              text        NOT NULL,     -- waiting_payment | approved | completed | (status internal lain)
  submitted_at        timestamptz NOT NULL,
  purpose             text,                     -- keperluan
  print_location      text,                     -- satuan penerbit: Polsek/Polres/Polda
  classification      text        CHECK (classification IN ('DALAM NEGERI','LUAR NEGERI')),
  application_path    text,                     -- path dokumen PDF
  issued_at           timestamptz,              -- tanggal terbit (belum ada di API)
  valid_until         timestamptz,              -- masa berlaku (belum ada di API)
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_skck_pemohon ON pengajuan_skck (pemohon_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS ix_skck_status  ON pengajuan_skck (status);
COMMENT ON COLUMN pengajuan_skck.status IS 'API lookup hanya mengembalikan approved, completed, waiting_payment.';

-- 3. Pengajuan Izin Keramaian (data.crowd_permit[]) ----------------------------
CREATE TABLE IF NOT EXISTS pengajuan_izin_keramaian (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pemohon_id            bigint      NOT NULL REFERENCES pemohon(id) ON DELETE RESTRICT,
  registration_number   text        NOT NULL UNIQUE,
  status                text        NOT NULL,   -- mis. schedule_confirmed
  submitted_at          timestamptz NOT NULL,
  activity_name         text        NOT NULL,
  activity_type_name    text,
  requested_review_date date,
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_ik_pemohon ON pengajuan_izin_keramaian (pemohon_id, submitted_at DESC);

-- 4. Daftar status VC (BitstringStatusList, untuk pencabutan) -----------------
CREATE TABLE IF NOT EXISTS vc_status_list (
  id             int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  url            text NOT NULL UNIQUE,              -- statusListCredential
  status_purpose text NOT NULL DEFAULT 'revocation' CHECK (status_purpose IN ('revocation','suspension')),
  size           int  NOT NULL DEFAULT 131072 CHECK (size > 0),
  next_index     int  NOT NULL DEFAULT 0,
  created_at     timestamptz NOT NULL DEFAULT now()
);

-- 5. Verifiable Credential yang diterbitkan ------------------------------------
CREATE TABLE IF NOT EXISTS verifiable_credential (
  id                   text PRIMARY KEY,                      -- urn:uuid:...
  credential_type      text NOT NULL CHECK (credential_type IN ('SKCKCredential','CrowdPermitCredential')),
  pemohon_id           bigint NOT NULL REFERENCES pemohon(id) ON DELETE RESTRICT,
  skck_id              char(26) REFERENCES pengajuan_skck(id) ON DELETE RESTRICT,
  izin_keramaian_id    bigint   REFERENCES pengajuan_izin_keramaian(id) ON DELETE RESTRICT,
  issuer_did           text NOT NULL,
  subject_did          text,
  valid_from           timestamptz NOT NULL,
  valid_until          timestamptz,
  status_list_id       int REFERENCES vc_status_list(id),
  status_list_index    int CHECK (status_list_index >= 0),
  revoked_at           timestamptz,
  revocation_reason    text,
  proof_type           text NOT NULL DEFAULT 'DataIntegrityProof',
  cryptosuite          text NOT NULL DEFAULT 'ecdsa-rdfc-2019',
  verification_method  text NOT NULL,                         -- did:...#key-1
  credential           jsonb NOT NULL,                        -- VC lengkap yang sudah ditandatangani
  created_at           timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT vc_satu_sumber CHECK (
    (credential_type = 'SKCKCredential'        AND skck_id IS NOT NULL AND izin_keramaian_id IS NULL) OR
    (credential_type = 'CrowdPermitCredential' AND izin_keramaian_id IS NOT NULL AND skck_id IS NULL)),
  CONSTRAINT vc_masa_berlaku CHECK (valid_until IS NULL OR valid_until > valid_from),
  CONSTRAINT vc_status_unik UNIQUE (status_list_id, status_list_index)
);
CREATE INDEX IF NOT EXISTS ix_vc_pemohon ON verifiable_credential (pemohon_id);
CREATE INDEX IF NOT EXISTS ix_vc_skck    ON verifiable_credential (skck_id) WHERE skck_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_vc_ik      ON verifiable_credential (izin_keramaian_id) WHERE izin_keramaian_id IS NOT NULL;

-- 6. Klien API (App-Id / Access-Key) -------------------------------------------
-- Access-Key TIDAK disimpan; hanya hash SHA-256-nya.
CREATE TABLE IF NOT EXISTS api_client (
  app_id           text PRIMARY KEY,
  name             text NOT NULL,
  access_key_hash  bytea NOT NULL,                 -- sha256(access_key)
  allowed_services text[] NOT NULL DEFAULT ARRAY['skck','crowd_permit'],
  active           boolean NOT NULL DEFAULT true,
  created_at       timestamptz NOT NULL DEFAULT now(),
  last_used_at     timestamptz
);

-- 7. Log akses lookup (audit akses data pribadi) -------------------------------
CREATE TABLE IF NOT EXISTS api_access_log (
  id           bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  app_id       text REFERENCES api_client(app_id),
  nik_hash     bytea NOT NULL,                     -- sha256(nik), NIK tidak disimpan polos
  services     text[] NOT NULL,
  http_status  smallint NOT NULL,
  result_count int,
  client_ip    inet,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_log_app_waktu ON api_access_log (app_id, created_at DESC);

-- Trigger updated_at -----------------------------------------------------------
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['pemohon','pengajuan_skck','pengajuan_izin_keramaian'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated ON layanan.%1$s', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated BEFORE UPDATE ON layanan.%1$s FOR EACH ROW EXECUTE FUNCTION layanan.set_updated_at()', t);
  END LOOP;
END $$;

-- Fungsi verifikasi klien API ---------------------------------------------------
CREATE OR REPLACE FUNCTION layanan.verifikasi_klien(p_app_id text, p_access_key text)
RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT EXISTS (
    SELECT 1 FROM layanan.api_client
    WHERE app_id = p_app_id AND active
      AND access_key_hash = sha256(convert_to(p_access_key, 'UTF8')));
$$;

-- Fungsi lookup: bentuk sama dengan respons API --------------------------------
-- SELECT layanan.lookup('3174012345678901', ARRAY['skck','crowd_permit']);
CREATE OR REPLACE FUNCTION layanan.lookup(p_nik text, p_services text[] DEFAULT ARRAY['skck','crowd_permit'])
RETURNS jsonb LANGUAGE sql STABLE AS $$
  WITH u AS (SELECT id, full_name FROM layanan.pemohon WHERE nik = p_nik)
  SELECT jsonb_build_object(
    'user', (SELECT jsonb_build_object('id', id, 'full_name', full_name) FROM u),
    'skck', CASE WHEN 'skck' = ANY(p_services) THEN COALESCE((
        SELECT jsonb_agg(jsonb_build_object(
          'id', s.id, 'registration_number', s.registration_number, 'status', s.status,
          'submitted_at', to_char(s.submitted_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
          'purpose', s.purpose, 'print_location', s.print_location,
          'classification', s.classification, 'application_path', s.application_path)
          ORDER BY s.submitted_at DESC)
        FROM layanan.pengajuan_skck s JOIN u ON u.id = s.pemohon_id
        WHERE s.status IN ('approved','completed','waiting_payment')), '[]'::jsonb)
      ELSE '[]'::jsonb END,
    'crowd_permit', CASE WHEN 'crowd_permit' = ANY(p_services) THEN COALESCE((
        SELECT jsonb_agg(jsonb_build_object(
          'id', c.id, 'registration_number', c.registration_number, 'status', c.status,
          'submitted_at', to_char(c.submitted_at AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
          'activity_name', c.activity_name, 'activity_type_name', c.activity_type_name,
          'requested_review_date', c.requested_review_date)
          ORDER BY c.submitted_at DESC)
        FROM layanan.pengajuan_izin_keramaian c JOIN u ON u.id = c.pemohon_id), '[]'::jsonb)
      ELSE '[]'::jsonb END);
$$;

-- Tampilan status VC -----------------------------------------------------------
CREATE OR REPLACE VIEW layanan.v_status_vc AS
SELECT vc.id, vc.credential_type, p.full_name, vc.valid_from, vc.valid_until,
       CASE WHEN vc.revoked_at IS NOT NULL THEN 'dicabut'
            WHEN vc.valid_until IS NOT NULL AND vc.valid_until < now() THEN 'kedaluwarsa'
            ELSE 'aktif' END AS status
FROM layanan.verifiable_credential vc
JOIN layanan.pemohon p ON p.id = vc.pemohon_id;

